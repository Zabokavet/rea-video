"""project.yaml: the single source of truth for a video.

Minimal example (see examples/ for complete ones):

    title: The Citadel
    language: ht            # en | fr | es | pt-br | ht | it | de | hi | any MMS code
    format: "16:9"          # 16:9 | 9:16 | 1:1 | 4:5
    style: documentary      # see `rea-studio styles`
    voice: {voice: auto, gender: male}
    music: {engine: score, mood: historical}
    visual_style: "..."     # style bible appended to every frame prompt
    characters: {henri: {description: "...", seed: 4242, voice: am_michael}}
    locations:  {citadel: {description: "..."}}
    scenes:
      - narration: "..."
        visual: "wide aerial shot of ..."
        location: citadel
        camera: parallax_in      # optional; else chosen from the style
        motion: camera           # camera | animate | wan
        title: "1805"            # optional on-screen text (Title | Chapter | Lower | Top via title_style)
        sfx: [wind, whoosh@0]
"""
from __future__ import annotations

import re
from pathlib import Path

import yaml

from . import languages, styles

RES = {"16:9": (1920, 1080), "9:16": (1080, 1920), "1:1": (1080, 1080), "4:5": (1080, 1350), "21:9": (2560, 1080)}
PREVIEW_RES = {"16:9": (1280, 720), "9:16": (720, 1280), "1:1": (720, 720), "4:5": (720, 900), "21:9": (1680, 720)}


class ProjectError(ValueError):
    pass


def load(path: str | Path) -> dict:
    path = Path(path)
    data = yaml.safe_load(path.read_text(encoding="utf-8")) or {}
    data["_path"] = str(path.resolve())
    data["_dir"] = str(path.resolve().parent)
    return normalize(data)


def normalize(p: dict) -> dict:
    if not p.get("scenes"):
        raise ProjectError("project has no scenes")
    p.setdefault("title", "Untitled")
    p["language"] = languages.get(str(p.get("language", "en"))).code
    st = styles.get(p.get("style", "documentary"))
    st.update(p.get("style_overrides") or {})
    p["_style"] = st
    p["format"] = str(p.get("format") or st["aspect"])
    if p["format"] not in RES:
        raise ProjectError(f"format must be one of {list(RES)}")
    p.setdefault("fps", 24 if st["name"] in ("cinematic", "storytelling") else 30)
    p.setdefault("seed", 1234)
    p.setdefault("voice", {})
    if isinstance(p["voice"], str):
        p["voice"] = {"voice": p["voice"]}
    p.setdefault("music", {})
    if isinstance(p["music"], str):
        p["music"] = {"mood": p["music"]}
    p.setdefault("characters", {})
    p.setdefault("locations", {})
    p.setdefault("visual_style", st["visual_suffix"])
    for i, s in enumerate(p["scenes"]):
        if isinstance(s, str):
            s = p["scenes"][i] = {"narration": s}
        s.setdefault("id", f"s{i + 1:02d}")
        s.setdefault("narration", "")
        s.setdefault("visual", s.get("prompt", ""))
        if not s["visual"] and not s.get("image") and not s.get("video"):
            raise ProjectError(f"scene {s['id']} needs `visual` (prompt), `image` or `video`")
        for c in s.get("characters", []) or []:
            if c not in p["characters"]:
                raise ProjectError(f"scene {s['id']} uses unknown character '{c}'")
        if s.get("location") and s["location"] not in p["locations"]:
            raise ProjectError(f"scene {s['id']} uses unknown location '{s['location']}'")
        if s.get("transition") and s["transition"] not in styles.XFADES:
            raise ProjectError(f"scene {s['id']}: transition must be one of {styles.XFADES}")
        for k in ("image", "video", "voice_file"):
            if s.get(k) and not Path(s[k]).is_absolute():
                s[k] = str(Path(p["_dir"]) / s[k])
    return p


def slug(text: str) -> str:
    import unicodedata
    t = unicodedata.normalize("NFKD", text).encode("ascii", "ignore").decode()
    return re.sub(r"[^a-z0-9]+", "-", t.lower()).strip("-")[:60] or "video"


def plan_scenes(duration_s: float, lang: str, style: str) -> tuple[int, int]:
    """-> (number of scenes, words per scene) for a target runtime."""
    st = styles.get(style)
    lo, hi = st["scene_seconds"]
    per = (lo + hi) / 2
    n = max(1, round(duration_s / per))
    wpm = languages.get(lang).words_per_minute
    from .tts import DELIVERY
    wpm *= DELIVERY.get(st["delivery"], DELIVERY["neutral"])["speed"]
    words_total = duration_s / 60 * wpm * 0.88  # leave air for pauses & transitions
    return n, max(4, round(words_total / n))


def skeleton(topic: str, lang: str = "en", duration: float = 60, aspect: str | None = None,
             style: str = "documentary") -> str:
    n, wps = plan_scenes(duration, lang, style)
    st = styles.get(style)
    lines = [
        f"# Generated by `rea-studio new`. Fill every TODO, then: rea-studio make {slug(topic)}/project.yaml",
        f"# Target: ~{duration:.0f}s -> {n} scenes x ~{wps} words of narration each ({languages.get(lang).name}).",
        f"title: {yaml.safe_dump(topic, allow_unicode=True).strip().splitlines()[0]}",
        f"language: {languages.get(lang).code}",
        f'format: "{aspect or st["aspect"]}"',
        f"style: {style}",
        f"duration: {duration:.0f}",
        "voice: {voice: auto, gender: male}   # rea-studio voices --lang " + languages.get(lang).code,
        f"music: {{engine: score, mood: {st['music']}}}",
        f"visual_style: \"{st['visual_suffix']}\"",
        "characters: {}   # name: {description: 'age, face, hair, clothing...', seed: 1234}",
        "locations: {}    # name: {description: 'place, era, lighting...'}",
        "scenes:",
    ]
    for i in range(n):
        lines += [f"  - narration: \"TODO scene {i + 1}: ~{wps} words\"",
                  f"    visual: \"TODO shot description (subject, action, framing, light)\""]
    return "\n".join(lines) + "\n"


def resolution(p: dict, preview: bool = False) -> tuple[int, int]:
    return (PREVIEW_RES if preview else RES)[p["format"]]
